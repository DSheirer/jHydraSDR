package io.github.dsheirer.hydrasdr.internal;

import static java.lang.foreign.MemoryLayout.PathElement.groupElement;
import static java.lang.foreign.MemoryLayout.paddingLayout;
import static java.lang.foreign.MemoryLayout.sequenceLayout;
import static java.lang.foreign.MemoryLayout.structLayout;
import static java.lang.foreign.ValueLayout.ADDRESS;
import static java.lang.foreign.ValueLayout.JAVA_BYTE;
import static java.lang.foreign.ValueLayout.JAVA_FLOAT;
import static java.lang.foreign.ValueLayout.JAVA_INT;
import static java.lang.foreign.ValueLayout.JAVA_LONG;
import static java.lang.foreign.ValueLayout.JAVA_SHORT;

import java.lang.foreign.GroupLayout;
import java.lang.foreign.MemoryLayout;
import java.lang.foreign.MemorySegment;
import java.nio.charset.StandardCharsets;

/**
 * Memory layouts of the structures in {@code hydrasdr.h}.
 *
 * <p>These are written by hand rather than generated by jextract because every
 * field has a fixed width: unlike jextract's {@code uint64_t} mapping, which
 * goes through {@code long} and is wrong on Windows, a single set of layouts is
 * correct on all supported platforms.
 */
public final class Layouts {
    private static final int COMPONENT_NAME_LENGTH = 32;
    private static final int RF_PORT_NAME_LENGTH = 16;
    private static final int DEVICE_NAME_LENGTH = 32;
    private static final int FIRMWARE_VERSION_LENGTH = 128;

    /** Maximum number of entries in {@code hydrasdr_device_info_t.components}. */
    public static final int MAX_COMPONENTS = 2;
    /** Maximum number of entries in {@code hydrasdr_device_info_t.rf_port_info}. */
    public static final int MAX_RF_PORTS = 32;

    /** {@code hydrasdr_lib_version_t}. */
    public static final GroupLayout LIB_VERSION = structLayout(
        JAVA_INT.withName("major_version"),
        JAVA_INT.withName("minor_version"),
        JAVA_INT.withName("revision"));

    /** {@code hydrasdr_transfer_t}. */
    public static final GroupLayout TRANSFER = structLayout(
        ADDRESS.withName("device"),
        ADDRESS.withName("ctx"),
        ADDRESS.withName("samples"),
        JAVA_INT.withName("sample_count"),
        paddingLayout(ADDRESS.byteSize() - JAVA_INT.byteSize()),
        JAVA_LONG.withName("dropped_samples"),
        JAVA_INT.withName("sample_type"),
        paddingLayout(4));

    /** {@code hydrasdr_read_partid_serialno_t}. */
    public static final GroupLayout PART_SERIAL = structLayout(
        sequenceLayout(2, JAVA_INT).withName("part_id"),
        sequenceLayout(4, JAVA_INT).withName("serial_no"));

    /** {@code hydrasdr_gain_range_t}. */
    public static final GroupLayout GAIN_RANGE = structLayout(
        JAVA_BYTE.withName("min_value"),
        JAVA_BYTE.withName("max_value"),
        JAVA_BYTE.withName("step_value"),
        JAVA_BYTE.withName("default_value"),
        sequenceLayout(4, JAVA_BYTE).withName("reserved"));

    /** {@code hydrasdr_gain_info_t}. */
    public static final GroupLayout GAIN_INFO = structLayout(
        JAVA_BYTE.withName("type"),
        JAVA_BYTE.withName("value"),
        JAVA_BYTE.withName("min_value"),
        JAVA_BYTE.withName("max_value"),
        JAVA_BYTE.withName("step_value"),
        JAVA_BYTE.withName("default_value"),
        JAVA_BYTE.withName("flags"),
        JAVA_BYTE.withName("reserved"));

    /** {@code hydrasdr_component_info_t}. */
    public static final GroupLayout COMPONENT_INFO = structLayout(
        JAVA_BYTE.withName("type"),
        sequenceLayout(3, JAVA_BYTE).withName("reserved_type"),
        sequenceLayout(COMPONENT_NAME_LENGTH, JAVA_BYTE).withName("name"),
        JAVA_INT.withName("register_count"),
        sequenceLayout(6, JAVA_INT).withName("reserved"));

    /** {@code hydrasdr_temperature_t}. */
    public static final GroupLayout TEMPERATURE = structLayout(
        JAVA_FLOAT.withName("temperature_celsius"),
        JAVA_FLOAT.withName("temperature_fahrenheit"),
        JAVA_BYTE.withName("valid"),
        sequenceLayout(7, JAVA_BYTE).withName("reserved"));

    /** {@code hydrasdr_rf_port_info_t}. */
    public static final GroupLayout RF_PORT_INFO = structLayout(
        sequenceLayout(RF_PORT_NAME_LENGTH, JAVA_BYTE).withName("name"),
        JAVA_LONG.withName("min_frequency"),
        JAVA_LONG.withName("max_frequency"),
        JAVA_BYTE.withName("has_bias_tee"),
        sequenceLayout(7, JAVA_BYTE).withName("bias_tee_reserved"),
        JAVA_FLOAT.withName("bias_tee_voltage"),
        JAVA_FLOAT.withName("bias_tee_max_current_milliamp"),
        sequenceLayout(8, JAVA_BYTE).withName("reserved"));

    /** {@code hydrasdr_streaming_stats_t}. */
    public static final GroupLayout STREAMING_STATS = structLayout(
        JAVA_LONG.withName("buffers_received"),
        JAVA_LONG.withName("buffers_processed"),
        JAVA_LONG.withName("buffers_dropped"),
        sequenceLayout(5, JAVA_LONG).withName("reserved"));

    /** {@code hydrasdr_device_info_t}, which is exactly 4096 bytes on every platform. */
    public static final GroupLayout DEVICE_INFO = structLayout(
        JAVA_SHORT.withName("struct_version_major"),
        JAVA_SHORT.withName("struct_version_minor"),
        JAVA_SHORT.withName("struct_version_revision"),
        JAVA_SHORT.withName("struct_reserved"),
        JAVA_BYTE.withName("board_id"),
        sequenceLayout(7, JAVA_BYTE).withName("board_reserved"),
        sequenceLayout(DEVICE_NAME_LENGTH, JAVA_BYTE).withName("board_name"),
        sequenceLayout(FIRMWARE_VERSION_LENGTH, JAVA_BYTE).withName("firmware_version"),
        PART_SERIAL.withName("part_serial"),
        JAVA_INT.withName("features"),
        sequenceLayout(3, JAVA_INT).withName("features_reserved"),
        GAIN_RANGE.withName("lna_gain"),
        sequenceLayout(4, GAIN_RANGE).withName("gain1_res"),
        GAIN_RANGE.withName("rf_gain"),
        sequenceLayout(4, GAIN_RANGE).withName("gain2_res"),
        GAIN_RANGE.withName("mixer_gain"),
        sequenceLayout(4, GAIN_RANGE).withName("gain3_res"),
        GAIN_RANGE.withName("filter_gain"),
        sequenceLayout(4, GAIN_RANGE).withName("gain4_res"),
        GAIN_RANGE.withName("vga_gain"),
        sequenceLayout(4, GAIN_RANGE).withName("gain5_res"),
        GAIN_RANGE.withName("linearity_gain"),
        GAIN_RANGE.withName("sensitivity_gain"),
        sequenceLayout(4, GAIN_RANGE).withName("gain6_res"),
        JAVA_BYTE.withName("component_count"),
        sequenceLayout(7, JAVA_BYTE).withName("component_reserved"),
        sequenceLayout(MAX_COMPONENTS, COMPONENT_INFO).withName("components"),
        JAVA_LONG.withName("min_frequency"),
        JAVA_LONG.withName("max_frequency"),
        sequenceLayout(8, JAVA_INT).withName("freq_res"),
        JAVA_INT.withName("rf_ports"),
        JAVA_BYTE.withName("rf_port_count"),
        sequenceLayout(3, JAVA_BYTE).withName("rf_port_reserved"),
        sequenceLayout(MAX_RF_PORTS, RF_PORT_INFO).withName("rf_port_info"),
        sequenceLayout(8, JAVA_INT).withName("rf_ports_res"),
        JAVA_SHORT.withName("gpio_count"),
        sequenceLayout(6, JAVA_BYTE).withName("gpio_reserved_1"),
        sequenceLayout(4, JAVA_INT).withName("gpio_res"),
        JAVA_SHORT.withName("sample_types"),
        sequenceLayout(3, JAVA_SHORT).withName("sample_type_reserved"),
        sequenceLayout(2, JAVA_INT).withName("sample_res"),
        JAVA_FLOAT.withName("typical_power_mw"),
        JAVA_FLOAT.withName("max_power_mw"),
        JAVA_FLOAT.withName("max_safe_temp_celsius"),
        JAVA_FLOAT.withName("max_safe_temp_fahrenheit"),
        sequenceLayout(4, JAVA_INT).withName("power_res"),
        JAVA_BYTE.withName("current_decimation_mode"),
        JAVA_BYTE.withName("current_packing"),
        JAVA_BYTE.withName("bandwidth_auto_selected"),
        JAVA_BYTE.withName("current_adc_bits"),
        JAVA_INT.withName("current_decimation_factor"),
        JAVA_INT.withName("current_bandwidth"),
        JAVA_INT.withName("current_samplerate"),
        JAVA_INT.withName("current_hw_samplerate"),
        JAVA_INT.withName("current_sample_type"),
        sequenceLayout(2, JAVA_INT).withName("config_state_reserved2"),
        sequenceLayout(189, JAVA_LONG).withName("reserved"));

    private Layouts() {
    }

    /** Returns the byte offset of a named field of a structure. */
    public static long offset(MemoryLayout layout, String field) {
        return layout.byteOffset(groupElement(field));
    }

    /** Reads an unsigned 8-bit field. */
    public static int u8(MemorySegment segment, MemoryLayout layout, String field) {
        return Byte.toUnsignedInt(segment.get(JAVA_BYTE, offset(layout, field)));
    }

    /** Reads an unsigned 16-bit field. */
    public static int u16(MemorySegment segment, MemoryLayout layout, String field) {
        return Short.toUnsignedInt(segment.get(JAVA_SHORT, offset(layout, field)));
    }

    /** Reads an unsigned 32-bit field. */
    public static long u32(MemorySegment segment, MemoryLayout layout, String field) {
        return Integer.toUnsignedLong(segment.get(JAVA_INT, offset(layout, field)));
    }

    /** Reads a 64-bit field. */
    public static long i64(MemorySegment segment, MemoryLayout layout, String field) {
        return segment.get(JAVA_LONG, offset(layout, field));
    }

    /** Reads a 32-bit floating point field. */
    public static float f32(MemorySegment segment, MemoryLayout layout, String field) {
        return segment.get(JAVA_FLOAT, offset(layout, field));
    }

    /** Returns the part of a structure that holds a nested field. */
    public static MemorySegment slice(MemorySegment segment, GroupLayout layout, String field) {
        return segment.asSlice(offset(layout, field), layout.select(groupElement(field)).byteSize());
    }

    /** Reads a character array field that may fill its space without a terminator. */
    public static String string(MemorySegment segment, GroupLayout layout, String field) {
        MemorySegment chars = slice(segment, layout, field);
        int length = 0;
        while (length < chars.byteSize() && chars.get(JAVA_BYTE, length) != 0) {
            length++;
        }
        return new String(chars.asSlice(0, length).toArray(JAVA_BYTE), StandardCharsets.UTF_8);
    }
}
